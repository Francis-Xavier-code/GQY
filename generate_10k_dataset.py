dataset = []
ts_counter = 1785800001

# 通过多维排列组合生成 10,000+ 条不重复、自然流畅的高质量样本
for p in pets:
    for prefix in user_prefix:
        for suffix in context_suffixes:
            for u_template, a_template in scenarios:
                user_msg = f"{prefix}{u_template}"
                assistant_msg = a_template.format(pet=p)
                if suffix:
                    assistant_msg = f"{assistant_msg}，{suffix}"
                
                dataset.append({
                    "ts": ts_counter,
                    "mode": "chat",
                    "user": user_msg,
                    "assistant": assistant_msg,
                    "tools": []
                })
                ts_counter += 10
                if len(dataset) >= 10500:
                    break
            if len(dataset) >= 10500:
                break
        if len(dataset) >= 10500:
            break
    if len(dataset) >= 10500:
        break

target_file = "/Users/mac/Desktop/GQY/data/finetune/turns.jsonl"
with open(target_file, "w", encoding="utf-8") as f:
    for item in dataset:
        f.write(json.dumps(item, ensure_ascii=False) + chr(10))

print(f"Successfully generated 10k+ dataset: {len(dataset)} entries in {target_file}")
